// Генератор маршрута поступления.
//
// Календарь построен по фактическому циклу ЕНТ-2026 (источник — НЦТ) и сдвинут
// на кампанию 2027 года. Официальные даты 2027 на момент сборки не объявлены,
// поэтому все календарные шаги помечены как ориентировочные.

import { pairName, cityName, thresholdFor } from '../data/taxonomy.js';
import { projectedScore } from './scoring.js';

export const CALENDAR_NOTE =
  'Даты приведены по циклу ЕНТ-2026: регистрация на основное ЕНТ шла с 11 по 25 апреля, ' +
  'само тестирование — с 10 мая по 10 июля. Даты кампании 2027 года официально ещё ' +
  'не объявлены, поэтому проверяйте их на testcenter.kz.';

export const CATEGORIES = {
  academic: { name: 'Учёба и подготовка' },
  exam: { name: 'Экзамены' },
  docs: { name: 'Документы' },
  deadline: { name: 'Дедлайн' },
  activity: { name: 'Активности' },
};

const T = (o) => ({ demo: false, ...o });

export function buildPlan(profile, target) {
  const { score: proj } = projectedScore(profile);
  const program = target ? target.program : null;
  const gap = program && program.cutoff ? program.cutoff - proj : 0;
  const needsPoints = gap > 0;
  const steps = [];

  // ——— Осень 2026: определиться и измерить стартовую точку ———
  steps.push(T({
    id: 'narrow',
    when: 'Сентябрь — октябрь 2026',
    cat: 'academic',
    title: 'Сузить выбор до трёх групп программ',
    detail:
      (profile.interests || []).length > 2
        ? 'Вы выбрали больше двух направлений. Оставьте три программы из списка ' +
          'рекомендаций: одну целевую, одну реалистичную и одну запасную.'
        : 'Возьмите три программы из рекомендаций: целевую, реалистичную и запасную. ' +
          'Конкурс на грант идёт на группу программ, а не на конкретную специальность.',
  }));

  steps.push(T({
    id: 'diagnostic',
    when: 'Октябрь 2026',
    cat: 'academic',
    title: 'Пройти пробный тест по своей паре предметов',
    detail:
      `Пробные тесты есть на сайте НЦТ. Сдайте полный вариант по паре ` +
      `«${pairName(profile.pair)}» и зафиксируйте реальный балл — дальше вся ` +
      'подготовка строится от него, а не от ощущений.',
    source: { label: 'Пробные тесты НЦТ', url: 'https://testcenter.kz/' },
  }));

  if (needsPoints) {
    steps.push(T({
      id: 'prep-gap',
      when: 'Октябрь 2026 — март 2027',
      cat: 'academic',
      title: `Добрать ${gap} баллов до проходного`,
      detail:
        `Проходной балл вашей целевой программы — ${program.cutoff}, ваш ориентир — ${proj}. ` +
        `Разрыв ${gap} баллов. Профильные предметы весят больше всего: сосредоточьтесь на ` +
        `${pairName(profile.pair).toLowerCase()} и разбирайте ошибки после каждого пробного теста.`,
      demo: true,
    }));
  } else {
    steps.push(T({
      id: 'prep-hold',
      when: 'Октябрь 2026 — март 2027',
      cat: 'academic',
      title: 'Удержать балл и подстраховать запасные варианты',
      detail:
        `Ваш ориентир ${proj} уже выше проходного балла целевой программы. ` +
        'Задача — не потерять форму: один полный пробный тест в месяц и разбор ошибок. ' +
        'Разрыв в 5–7 баллов легко теряется на невнимательности.',
    }));
  }

  // ——— Языковые и творческие требования ———
  if (program && program.langs.length === 1 && program.langs[0] === 'en'
      && !(profile.langs || []).includes('en')) {
    steps.push(T({
      id: 'english',
      when: 'Ноябрь 2026 — май 2027',
      cat: 'academic',
      title: 'Подтянуть английский до уровня обучения',
      detail:
        `${program.short} учит только на английском, а вы его не указали. ` +
        'Уточните в приёмной комиссии, нужен ли сертификат IELTS и какой балл, ' +
        'и начинайте заранее — это не решается за месяц.',
    }));
  }

  if (program && program.pairs.includes('creative')) {
    steps.push(T({
      id: 'creative',
      when: 'Декабрь 2026 — май 2027',
      cat: 'exam',
      title: 'Готовить портфолио к творческому экзамену',
      detail:
        `На «${program.name}» отбор идёт через творческий экзамен. Он проходит в самом ` +
        'вузе, даты и требования к работам публикует приёмная комиссия — запросите их ' +
        'в декабре, а не в мае.',
      source: { label: `Приёмная комиссия ${program.short}`, url: program.site },
    }));
  }

  // ——— Зимняя и весенняя попытки ———
  steps.push(T({
    id: 'reg-jan',
    when: '20 — 30 декабря 2026',
    cat: 'deadline',
    title: 'Зарегистрироваться на январское ЕНТ',
    detail:
      'Январское, мартовское и августовское ЕНТ дают поступление только на платное, ' +
      'но это лучшая тренировка в реальных условиях. Регистрация — на app.testcenter.kz ' +
      'или в приложении UTO.',
    source: { label: 'НЦТ: сроки регистрации', url: 'https://testcenter.kz/' },
    demo: true,
  }));

  steps.push(T({
    id: 'jan-ent',
    when: 'Январь 2027',
    cat: 'exam',
    title: 'Сдать январское ЕНТ как репетицию',
    detail:
      'Формат: три обязательных предмета плюс два профильных, 4 часа. ' +
      'После теста вы получите тематический анализ — он точно покажет, какие темы проваливаются.',
  }));

  steps.push(T({
    id: 'analysis',
    when: 'Февраль 2027',
    cat: 'academic',
    title: 'Разобрать тематический анализ января',
    detail:
      'Возьмите отчёт по темам и выпишите пять самых слабых. Следующие два месяца ' +
      'подготовки — только по ним. Это самый дешёвый способ добрать баллы.',
  }));

  steps.push(T({
    id: 'mar-ent',
    when: 'Март 2027',
    cat: 'exam',
    title: 'Мартовское ЕНТ — контрольный замер',
    detail:
      'Вторая тренировочная попытка. Если балл не вырос, до основного ЕНТ остаётся ' +
      'два месяца — этого достаточно, чтобы изменить способ подготовки, но не сам план.',
  }));

  // ——— Основная кампания ———
  steps.push(T({
    id: 'reg-main',
    when: '11 — 25 апреля 2027',
    cat: 'deadline',
    title: 'Регистрация на основное ЕНТ',
    detail:
      'Здесь вы выбираете дату, время, пункт тестирования и пару профильных предметов — ' +
      `в вашем случае «${pairName(profile.pair)}». С 11 по 16 апреля заявление можно подать ` +
      'один раз, с 17 по 25 апреля — второй. Это вход в конкурс на грант.',
    source: { label: 'НЦТ: основное ЕНТ', url: 'https://testcenter.kz/' },
    demo: true,
  }));

  steps.push(T({
    id: 'main-ent',
    when: 'Май — июль 2027',
    cat: 'exam',
    title: 'Основное ЕНТ, до двух попыток',
    detail:
      'В конкурс на грант идёт лучший результат из двух попыток. Первую попытку лучше ' +
      'ставить раньше, чтобы осталось время на вторую.',
    source: { label: 'НЦТ', url: 'https://testcenter.kz/' },
    demo: true,
  }));

  steps.push(T({
    id: 'docs',
    when: 'Июнь 2027',
    cat: 'docs',
    title: 'Собрать пакет документов',
    detail:
      'Аттестат, удостоверение личности, медицинская справка 086-У, фотографии 3×4, ' +
      'сертификат ЕНТ. Точный список каждый вуз публикует у себя — сверьтесь с ним заранее.',
    source: program
      ? { label: `Приёмная комиссия ${program.short}`, url: program.site }
      : null,
  }));

  steps.push(T({
    id: 'grant-apply',
    when: 'Июль 2027',
    cat: 'deadline',
    title: 'Подать заявление на конкурс грантов',
    detail:
      'Заявление подаётся через eGov или напрямую в приёмную комиссию. В нём указываются ' +
      'группы программ по приоритету — порядок важен, потому что конкурс идёт сверху вниз.',
    source: { label: 'eGov: конкурс грантов', url: 'https://egov.kz/' },
    demo: true,
  }));

  if (profile.budget === 'grant') {
    steps.push(T({
      id: 'plan-b',
      when: 'Июль 2027',
      cat: 'docs',
      title: 'Подготовить план Б без гранта',
      detail:
        'Вы рассчитываете только на грант, поэтому нужен второй сценарий: программы с ' +
        'проходным баллом на 10–15 ниже, региональные вузы, августовское ЕНТ для платного ' +
        'приёма или колледж с переходом в вуз.',
    }));
  }

  steps.push(T({
    id: 'enroll',
    when: 'Август 2027',
    cat: 'docs',
    title: 'Зачисление и договор',
    detail:
      program
        ? `Если грант получен — подписываете договор в ${program.short} и подаёте на общежитие. ` +
          'Если нет — августовское ЕНТ даёт ещё одну попытку для платного приёма.'
        : 'Подписание договора, заявление на общежитие. При неудаче — августовское ЕНТ ' +
          'для платного приёма.',
  }));

  // ——— Активности, усиливающие заявку ———
  steps.push(T({
    id: 'olympiad',
    when: 'Ноябрь 2026 — февраль 2027',
    cat: 'activity',
    title: 'Заявиться на предметную олимпиаду',
    detail:
      `Олимпиады по ${pairName(profile.pair).toLowerCase()} дают преимущество при равных ` +
      'баллах, а у призёров республиканского уровня появляется отдельный путь к гранту. ' +
      'Регистрация идёт через школу.',
  }));

  if (profile.gpa === 'top') {
    steps.push(T({
      id: 'altyn',
      when: 'Весь учебный год',
      cat: 'activity',
      title: 'Удержать «Алтын белгі»',
      detail:
        'При ваших оценках знак достижим, а он даёт преимущество в конкурсе на грант. ' +
        'Условия уточните у классного руководителя — они зависят от всех лет обучения.',
    }));
  }

  steps.push(T({
    id: 'visit',
    when: 'Февраль — апрель 2027',
    cat: 'activity',
    title: 'Съездить на день открытых дверей',
    detail:
      program
        ? `Посмотрите ${program.short} в ${cityName(program.city)} живьём и задайте приёмной ` +
          'комиссии два вопроса: сколько грантов было в прошлом году и какой был проходной балл.'
        : 'Дни открытых дверей — самый быстрый способ получить настоящие цифры по грантам.',
    source: program ? { label: program.site.replace('https://', ''), url: program.site } : null,
  }));

  return steps;
}

// Ближайший невыполненный шаг — то, что показывается как «следующее действие».
export function nextStep(steps, done) {
  return steps.find((s) => !done[s.id]) || null;
}

export function planProgress(steps, done) {
  const total = steps.length;
  const complete = steps.filter((s) => done[s.id]).length;
  return { total, complete, pct: total ? Math.round((complete / total) * 100) : 0 };
}

export function thresholdLabel(program) {
  return `Пороговый балл направления: ${thresholdFor(program)}`;
}
